def _pick_title(role: Role, i: int) -> str:
    """Role-neutral title: base title + neutral suffix (3 × 7 = up to 18 variants)."""
    variant = role["titles"][i % len(role["titles"])]
    suffix = _TITLE_SUFFIXES[(i // len(role["titles"])) % len(_TITLE_SUFFIXES)]
    return f"{variant}{suffix}"


def _sample_skills(role: Role, rng: random.Random) -> list[str]:
    k = rng.randint(5, 8)
    chosen: list[str] = []
    for axis in role["dominant"]:
        chosen.append(rng.choice(role["skills"][axis]))
    weights = [2.0 if a in role["dominant"] else 1.0 for a in AXES]
    while len(chosen) < k:
        axis = rng.choices(AXES, weights=weights, k=1)[0]
        skill = rng.choice(role["skills"][axis])
        if skill not in chosen:
            chosen.append(skill)
    return chosen


def _years_word(years: int) -> str:
    if years % 10 == 1 and years % 100 != 11:
        return "год"
    if years % 10 in (2, 3, 4) and years % 100 not in (12, 13, 14):
        return "года"
    return "лет"


def _build_description(title: str, role: Role, skills: list[str], years: int, broad_outlook: bool, domain: str) -> str:
    """Structured multi-section job posting.

    Core skills come from the role's dominant axes, preferred skills from the
    remaining axes (including the erudition ``t_profile`` bucket). Broad-outlook
    roles additionally get a dedicated erudition line.
    """
    dominant_pool = {skill for axis in role["dominant"] for skill in role["skills"][axis]}
    core_skills = [skill for skill in skills if skill in dominant_pool]
    preferred_skills = [skill for skill in skills if skill not in dominant_pool]
    lines = [
        f"Требуется {title}.",
        "",
        f"О проекте: {_DOMAIN_INTROS[domain]}",
        "",
        "Чем предстоит заниматься:",
        *(f"- {duty}" for duty in role["duties"]),
        "",
        "Требования:",
        f"• Опыт работы от {years} {_years_word(years)}",
        "• Высшее профильное образование",
        f"• Знание: {', '.join(core_skills)}",
    ]
    if preferred_skills:
        lines += ["", "Желательно:", f"• {', '.join(preferred_skills)}"]
    if broad_outlook:
        lines += ["", f"Широкий кругозор в области {_DOMAIN_NAMES[domain]} (смежные направления, история и методология)."]
    lines += ["", "Условия: работа в научной команде, гибкий график, ДМС после испытательного срока."]
    return "\n".join(lines)


def _generate_domain(domain: str, count: int) -> None:
    roles = ROLES[domain]
    prefix = _DOMAIN_PREFIXES[domain]
    rng = random.Random(_DOMAIN_SEEDS[domain])

    vac_ids: list[str] = []
    titles: list[str] = []
    descriptions: list[str] = []
    skill_vac_ids: list[str] = []
    skill_phrases: list[str] = []
    experience_years: list[float] = []
    char_vac_ids: list[str] = []
    char_titles: list[str] = []
    char_axis_ids: list[str] = []
    char_labels: list[str] = []
    char_confidences: list[float] = []

    for i in range(count):
        role = roles[i % len(roles)]
        title = _pick_title(role, i // len(roles))
        skills = _sample_skills(role, rng)
        years = rng.randint(role["experience_years"][0], role["experience_years"][1])
        broad_outlook = len(role["skills"].get("t_profile", [])) >= 4
        description = _build_description(title, role, skills, years, broad_outlook, domain)
        vid = f"{prefix}_{i:05d}"
        vac_ids.append(vid)
        titles.append(title)
        descriptions.append(description)
        experience_years.append(float(years))
        for axis in role["dominant"]:
            char_vac_ids.append(vid)
            char_titles.append(title)
            char_axis_ids.append(axis)
            char_labels.append(_AXIS_LABELS[axis])
            char_confidences.append(1.0)
        for phrase in skills:
            skill_vac_ids.append(vid)
            skill_phrases.append(phrase)

    classified = pd.DataFrame({
        "vacancy_id": vac_ids,
        "title": titles,
        "description": descriptions,
        "stem_category": [STEM_CATEGORY] * count,
        "nli_scores_json": [None] * count,
    })
    skills_df = pd.DataFrame({
        "vacancy_id": skill_vac_ids,
        "skill_phrase": skill_phrases,
        "frequency": [1] * len(skill_vac_ids),
        "tfidf_weight": [1.0] * len(skill_vac_ids),
    })

    experience_df = pd.DataFrame({
        "vacancy_id": vac_ids,
        "experience_years": experience_years,
    })
    characteristics_df = pd.DataFrame({
        "vacancy_id": char_vac_ids,
        "extracted_title": char_titles,
        "characteristic_id": char_axis_ids,
        "characteristic_label": char_labels,
        "confidence": char_confidences,
    })

    out_dir = ROOT / "data" / domain
    write_parquet(classified, out_dir / "classified.parquet")
    write_parquet(skills_df, out_dir / "extracted_skills.parquet")
    write_parquet(experience_df, out_dir / "vacancy_experience.parquet")
    write_parquet(characteristics_df, out_dir / "characteristics.parquet")
    print(f"[{domain}] {count} vacancies, {len(skill_vac_ids)} skill rows → {out_dir}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate synthetic STEM vacancies.")
    parser.add_argument("--domain", choices=["physics", "biology", "chemistry"],
                        help="Domain to generate (default: all three)")
    parser.add_argument("--count", type=int, default=10000,
                        help="Vacancies per domain (default: 10000)")
    args = parser.parse_args()
    domains = [args.domain] if args.domain else list(_DOMAIN_PREFIXES)
    for domain in domains:
        _generate_domain(domain, args.count)


if __name__ == "__main__":
    main()
