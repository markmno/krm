def collect_vacancy(collector, conn, run_id, text, region_code=None, region_name=None):
    seen = set()
    try:
        vacancies = collector.collect_all(text=text, region_code=region_code)
    except Exception as e:
        print(f"  ERROR collecting {text} (region={region_name}): {e}")
        return 0

    for v in vacancies:
        vid = v["id"]
        if vid in seen:
            continue
        seen.add(vid)
        try:
            upsert_raw_vacancy(conn, run_id, vid, v)
        except Exception:
            pass
    return len(seen)


def main():
    conn = get_connection()
    init_tables(conn)
    run_id = f"trudvsem_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}"

    collector = TrudvsemCollector(rate_limit_rps=0.5)

    total_stored = 0
    start_time = time.time()

    try:
        for kw in STEM_KEYWORDS:
            api_total = collector.count(text=kw)
            print(f"\n[{kw}] API total: {api_total}")

            if api_total == 0:
                continue

            if api_total <= MAX_OFFSET:
                n = collect_vacancy(collector, conn, run_id, kw)
                total_stored += n
                print(f"  → stored {n} (running total: {total_stored})")
            else:
                print(f"  >{MAX_OFFSET} — partitioning by region")
                for rc, rname in REGION_CODES.items():
                    rc_total = collector.count(text=kw, region_code=rc)
                    if rc_total == 0:
                        continue
                    time.sleep(1)
                    print(f"    [{rname}] {rc_total}")
                    n = collect_vacancy(collector, conn, run_id, kw, rc, rname)
                    total_stored += n
                    print(f"    → stored {n}")

            elapsed = time.time() - start_time
            rate = total_stored / elapsed if elapsed > 0 else 0
            print(f"  [total: {total_stored} | {rate:.0f} rec/s | {elapsed/60:.0f} min]")

    finally:
        collector.close()

    elapsed = time.time() - start_time
    print(f"\n{'=' * 60}")
    print(f"DONE: {total_stored} records in {elapsed/60:.1f} min")
    print(f"Run ID: {run_id}")

    # Show final DB count
    final = conn.execute("SELECT COUNT(*) FROM raw_vacancies").fetchone()[0]
    print(f"DB total: {final}")
    conn.close()


if __name__ == "__main__":
    main()
